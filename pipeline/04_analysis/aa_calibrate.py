"""AA6: calibrate the significance test to the A/A tests (NOTES §8.1, approved by Sanjay 2026-11-10 23:33).

(a) Main method, quasi-binomial: phi = pooled chi-square / pooled degrees of freedom over the usable A/A tests; every later
    test divides its chi-square by phi (regressions multiply variances by phi). Checked by a split-half test: estimate phi on
    a random half of the A/A tests, measure the false-positive rate on the other half, and the reverse.
(b) Robustness, empirical threshold: the 95th percentile of chi-square / df across the usable A/A tests; a later test counts
    as significant under (b) when its chi-square / df exceeds it. Gives exactly 5% on the A/A tests by construction.
Reads build/04_analysis/aa_tests (from aa_check.py). Writes build/04_analysis/calibration.json (used by later steps) and
adds an AA6 section to docs/results/aa_check.md.
"""
import json
import os
import sys

import numpy as np
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from common import BUILD, DOCS, SPLIT, load_table  # noqa: E402

SEED = 20261110
ALPHA = 0.05

aa = load_table(f"04_analysis/{SPLIT}/aa_tests")
use = aa[aa.usable_causal.astype(bool)].reset_index(drop=True)
phi = float(use.chi2.sum() / use.df.sum())

rng = np.random.default_rng(SEED)
idx = rng.permutation(len(use))
half_a, half_b = use.iloc[idx[: len(use) // 2]], use.iloc[idx[len(use) // 2:]]


def fp_rate(test_half, phi_used):
    return float((stats.chi2.sf(test_half.chi2 / phi_used, test_half.df) < ALPHA).mean())


phi_a = float(half_a.chi2.sum() / half_a.df.sum())
phi_b = float(half_b.chi2.sum() / half_b.df.sum())
ratio = use.chi2 / use.df
threshold = float(np.quantile(ratio, 0.95))
cal = {
    "phi": phi, "n_aa_tests": len(use), "seed": SEED,
    "split_half": {"phi_half_a": phi_a, "phi_half_b": phi_b,
                   "fp_on_b_using_phi_a": fp_rate(half_b, phi_a), "fp_on_a_using_phi_b": fp_rate(half_a, phi_b)},
    "fp_all_aa_using_phi": fp_rate(use, phi),
    "empirical_threshold_chi2_per_df": threshold,
    "fp_all_aa_using_threshold": float((ratio > threshold).mean()),
}
json.dump(cal, open(os.path.join(BUILD, "04_analysis", SPLIT, "calibration.json"), "w"), indent=1)

pct = lambda x: f"{100 * x:.1f}%"  # noqa: E731
sh = cal["split_half"]
md = f"""
## AA6: calibration (approved 2026-11-10 23:33)

Generated by `pipeline/04_analysis/aa_calibrate.py` (seed {SEED}).

| | Result |
|---|---|
| (a) Dispersion factor φ (pooled chi-square ÷ degrees of freedom, {len(use)} A/A tests) | **{phi:.2f}**: click rates vary about {phi:.1f}× as much as coin flips; uncertainty widens by √φ = {phi ** 0.5:.2f} |
| Split-half check: φ from half A = {phi_a:.2f}, false positives on half B | {pct(sh['fp_on_b_using_phi_a'])} |
| Split-half check: φ from half B = {phi_b:.2f}, false positives on half A | {pct(sh['fp_on_a_using_phi_b'])} |
| All A/A tests with φ (not a fair check, same data) | {pct(cal['fp_all_aa_using_phi'])} (was 26.1% uncorrected) |
| (b) Empirical threshold: 95th percentile of chi-square ÷ df | **{threshold:.2f}** (gives {pct(cal['fp_all_aa_using_threshold'])} on the A/A tests by construction) |

**Reading it:** the correction brings false positives from 26% down to {pct(sh['fp_on_b_using_phi_a'])} and {pct(sh['fp_on_a_using_phi_b'])} on held-out halves: close to the 5% target but somewhat over, because a few tests are much noisier than the rest. That is why every later result is also reported under (b), and why a finding counts as robust only if it holds under both.
"""
p = os.path.join(DOCS, "results", SPLIT, "aa_check.md")
body = open(p, encoding="utf-8").read().split("\n## AA6")[0].rstrip("\n") + "\n"
open(p, "w", encoding="utf-8").write(body + md)
print(md)
