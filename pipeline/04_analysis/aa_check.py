"""A/A check AA1–AA5 (NOTES §8.1, approved by Sanjay 2026-11-10): does our test find "significant" differences
between identical tiles about 5% of the time, as it should?

Exploratory only (R2). Arms = individual packages (S5 keeps identical versions as separate rows for checks like this).
Writes build/04_analysis/aa_tests (one row per A/A test), build/04_analysis/aa_results.json and docs/results/aa_check.md.
"""
import json
import math
import os
import sys

import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from common import BUILD, DOCS, SPLIT, load_table, save_table  # noqa: E402

ALPHA = 0.05


def homogeneity_p(clicks, impressions):
    """AA1: chi-square test of homogeneity on the arms x (clicked, didn't click) table, df = arms - 1, no continuity
    correction. Returns (chi2, df, p, smallest expected click count)."""
    clicks = np.asarray(clicks, float); n = np.asarray(impressions, float)
    rate = clicks.sum() / n.sum()
    exp_c, exp_n = n * rate, n * (1 - rate)
    chi2 = float((((clicks - exp_c) ** 2) / exp_c).sum() + ((((n - clicks) - exp_n) ** 2) / exp_n).sum())
    df = len(clicks) - 1
    return chi2, df, float(stats.chi2.sf(chi2, df)), float(exp_c.min())


def wilson(k, n, z=1.959963984540054):
    p = k / n; d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def per_test(packages):
    rows = []
    for tid, g in packages.groupby("clickability_test_id", sort=True):
        chi2, df, p, emin = homogeneity_p(g.clicks, g.impressions)
        rows.append({"clickability_test_id": tid, "split": g.split.iloc[0], "n_arms": len(g), "impressions": int(g.impressions.sum()),
                     "clicks": int(g.clicks.sum()), "chi2": chi2, "df": df, "p": p, "min_expected_clicks": emin,
                     "usable_causal": bool(g.usable_causal.iloc[0]),
                     "max_editor_significance": float(g.significance.max()),
                     "editor_winner": bool((g.winner.astype(str) == "True").any())})
    return pd.DataFrame(rows)


def false_positive_rate(p):
    k, n = int((p < ALPHA).sum()), len(p)
    lo, hi = wilson(k, n)
    return {"n_tests": n, "n_significant": k, "rate": k / n, "ci95": [lo, hi], "pass": lo <= ALPHA <= hi}


if __name__ == "__main__":
    pk = load_table("02_clean/packages", split=SPLIT)
    aa = per_test(pk[pk.is_aa_test.astype(bool)])
    use = aa[aa.usable_causal]
    tenths = np.histogram(use.p, bins=np.linspace(0, 1, 11))[0] / len(use)
    ks = stats.kstest(use.p, "uniform")
    res = {
        "AA1": {"tests": len(use), "tests_with_expected_clicks_below_5": int((use.min_expected_clicks < 5).sum())},
        "AA2": false_positive_rate(use.p),
        "AA3": {"share_per_tenth": [round(float(x), 4) for x in tenths], "ks_stat": float(ks.statistic),
                "ks_p": float(ks.pvalue), "pass": bool(ks.pvalue >= 0.05)},
        "AA4": false_positive_rate(aa.p),
        "AA5": {"share_with_editor_score_95_or_more": float((use.max_editor_significance >= 95).mean()),
                "share_with_editor_winner": float(use.editor_winner.mean())},
    }
    save_table(aa, f"04_analysis/{SPLIT}/aa_tests")
    os.makedirs(os.path.join(BUILD, "04_analysis", SPLIT), exist_ok=True)
    json.dump(res, open(os.path.join(BUILD, "04_analysis", SPLIT, "aa_results.json"), "w"), indent=1)

    a2, a3, a4, a5 = res["AA2"], res["AA3"], res["AA4"], res["AA5"]
    pct = lambda x: f"{100 * x:.1f}%"  # noqa: E731
    md = f"""# A/A check ({SPLIT})

Generated by `pipeline/04_analysis/aa_check.py`. Method: NOTES §8.1 (approved 2026-11-10). Data: Upworthy Research Archive, {SPLIT} split (Matias et al., CC BY 4.0).

**Question:** when every version of a tile was identical, how often does our test call the click rates "significantly" different? A sound method should do so about 5% of the time.

| # | Result | Pass rule | Outcome |
|---|---|---|---|
| AA1 | {res['AA1']['tests']} usable A/A tests, one chi-square p-value each; {res['AA1']['tests_with_expected_clicks_below_5']} with an arm expecting fewer than 5 clicks | flagged, kept | — |
| AA2 | **{a2['n_significant']} of {a2['n_tests']} significant = {pct(a2['rate'])}** (95% interval {pct(a2['ci95'][0])} to {pct(a2['ci95'][1])}) | interval includes 5% | {'✅ pass' if a2['pass'] else '❌ fail'} |
| AA3 | p-values per tenth: {', '.join(pct(x) for x in a3['share_per_tenth'])}; Kolmogorov–Smirnov p = {a3['ks_p']:.3f} | ~10% each; KS p ≥ 0.05 | {'✅ pass' if a3['pass'] else '❌ fail'} |
| AA4 | All {a4['n_tests']} A/A tests incl. the excluded ones: {a4['n_significant']} significant = {pct(a4['rate'])} ({pct(a4['ci95'][0])} to {pct(a4['ci95'][1])}) | reported | — |
| AA5 | Upworthy's dashboard in these identical tests: some version scored 95+ on the editor "significance" score in {pct(a5['share_with_editor_score_95_or_more'])}; editors picked a "winner" in {pct(a5['share_with_editor_winner'])} | descriptive only (that score is not a p-value) | — |
"""
    os.makedirs(os.path.join(DOCS, "results", SPLIT), exist_ok=True)
    open(os.path.join(DOCS, "results", SPLIT, "aa_check.md"), "w", encoding="utf-8").write(md)
