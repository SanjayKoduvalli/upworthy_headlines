"""Bring the Headline Classifier's labels into the project (R14; NOTES §5.4).

Claude exports the classifier page's `results` collection as JSON files (one per call), then runs:
    python3 scripts/import_classifier_labels.py <folder with the exported results .json files> <tier>
It writes
  docs/validation/classifier_validation.md   the classifier vs. Sanjay's 100 blind labels, per model tier
  docs/validation/classifier_labels_<split>.csv.gz   the labels per unit (kept in the repo: the paid run is not re-done by the build)
  build/03_features/headline_labels.csv.gz   the labels per unit with 0/1 topic columns, for the pipeline
and stops if any unit of a split is missing or labeled twice with different answers.
"""
import collections
import glob
import gzip
import json
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "pipeline"))
from common import DOCS, save_table  # noqa: E402

SRC, TIER = sys.argv[1], sys.argv[2]
DATA = os.path.join(ROOT, "..", "classifier", "data") if len(sys.argv) < 4 else sys.argv[3]
G = {"f": "female", "m": "male", "b": "both", "n": "none"}
S = {"+": "positive", "0": "neutral", "-": "negative"}
TOPICS = json.load(open(os.path.join(DATA, "prompt.json"), encoding="utf-8"))["topics"]

docs = [json.load(open(f, encoding="utf-8")) for f in glob.glob(os.path.join(SRC, "**", "*.json"), recursive=True)]
docs = [d.get("data", d) for d in docs]
by = collections.defaultdict(dict)                          # (set, tier) -> batch -> labels
for d in docs:
    by[(d["set"], d["tier"])][d["batch"]] = d["labels"]


def kappa(a, b):
    n = len(a); cats = set(a) | set(b)
    po = sum(x == y for x, y in zip(a, b)) / n
    pe = sum((a.count(c) / n) * (b.count(c) / n) for c in cats)
    return (po - pe) / (1 - pe)


# ---- validation report ----
val = json.load(open(os.path.join(DATA, "validation.json"), encoding="utf-8"))
lines = ["# Classifier vs. Sanjay's blind labels (100 headlines)", "",
         "Generated by `scripts/import_classifier_labels.py`. Classifier = Claude with the fixed codebook-v2 prompt (R14). "
         "Topic match = Sanjay's single topic is among the classifier's tags (LGBTQ+ and women map to GEN; 'unclear' "
         "matches no tags). Earlier AI draft (v1, single topic) shown for reference.", "",
         "| Measure | AI draft v1 | " + " | ".join(t for (s, t) in sorted(by) if s == "validation") + " |",
         "|---|---|" + "---|" * sum(1 for (s, _) in by if s == "validation")]
res = {}
for (s, t) in sorted(by):
    if s != "validation":
        continue
    rows = [(it["human"], lab) for n, b in enumerate(val["batches"]) for it, lab in zip(b, by[(s, t)][n])]
    assert all(h_it["k"] == lab["k"] for n, b in enumerate(val["batches"]) for h_it, lab in zip(b, by[(s, t)][n]))
    hg, ag = [h["g"] for h, _ in rows], [a["g"] for _, a in rows]
    hs, as_ = [h["s"] for h, _ in rows], [a["s"] for _, a in rows]
    res[t] = {
        "Gender agreement": f"{sum(x == y for x, y in zip(hg, ag))}%", "Gender kappa": f"{kappa(hg, ag):.2f}",
        "Sentiment agreement": f"{sum(x == y for x, y in zip(hs, as_))}%", "Sentiment kappa": f"{kappa(hs, as_):.2f}",
        "Positive vs. negative flips": f"{sum({x, y} == {'+', '-'} for x, y in zip(hs, as_))}%",
        "Sanjay's topic among the tags": f"{sum((h['t'] in a['t']) if h['t'] else not a['t'] for h, a in rows)}%",
        "Tags per headline": f"{sum(len(a['t']) for _, a in rows) / len(rows):.1f}",
        "No topic (unclear)": f"{sum(not a['t'] for _, a in rows)}%"}
v1 = {"Gender agreement": "95%", "Gender kappa": "0.93", "Sentiment agreement": "72%", "Sentiment kappa": "0.58",
      "Positive vs. negative flips": "4%", "Sanjay's topic among the tags": "78% (one topic)", "Tags per headline": "1",
      "No topic (unclear)": "—"}
for m in v1:
    lines.append(f"| {m} | {v1[m]} | " + " | ".join(res[t][m] for t in sorted(res)) + " |")
open(os.path.join(DOCS, "validation", "classifier_validation.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
json.dump(res, open(os.path.join(DOCS, "validation", "classifier_validation.json"), "w"), indent=1)   # same numbers, machine-readable (R24)
# the 100 validation headlines with Sanjay's blind label and the classifier's (default model): data for the case-study demo
if ("validation", "default") in by:
    items = [{"k": it["k"], "h": it["h"], **({"e": it["e"]} if it.get("e") else {}), "human": it["human"],
              "ai": {"g": lab["g"], "s": lab["s"], "t": lab["t"]}}
             for n, b in enumerate(val["batches"]) for it, lab in zip(b, by[("validation", "default")][n])]
    json.dump(items, open(os.path.join(DOCS, "validation", "classifier_validation_items.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=0)
print("\n".join(lines))

# ---- labels per unit ----
frames = []
for split in ("exploratory", "confirmatory"):
    if not os.path.exists(os.path.join(DATA, f"{split}.json")):
        continue
    inp = json.load(open(os.path.join(DATA, f"{split}.json"), encoding="utf-8"))
    got = by.get((split, TIER), {})
    missing = [n for n in range(len(inp["batches"])) if n not in got]
    if missing:
        print(f"{split}: {len(missing)} of {len(inp['batches'])} calls not done yet; skipped")
        continue
    recs = []
    for n, b in enumerate(inp["batches"]):
        assert [it["k"] for it in b] == [lab["k"] for lab in got[n]], f"{split} batch {n}: keys don't match the input"
        for lab in got[n]:
            r = {"unit_key": lab["k"], "split": split, "gender": G[lab["g"]], "sentiment": S[lab["s"]]}
            r.update({f"topic_{c}": int(c in lab["t"]) for c in TOPICS})
            recs.append(r)
    df = pd.DataFrame(recs)
    assert df.unit_key.is_unique and len(df) == inp["n_units"]
    df["n_topics"] = df[[f"topic_{c}" for c in TOPICS]].sum(axis=1)
    df["topic_unclear"] = (df.n_topics == 0).astype(int)
    with gzip.open(os.path.join(DOCS, "validation", f"classifier_labels_{split}.csv.gz"), "wt", encoding="utf-8", newline="") as f:
        df.to_csv(f, index=False)
    frames.append(df)
    print(f"{split}: {len(df):,} units labeled with the {TIER} model")
if frames:
    save_table(pd.concat(frames, ignore_index=True), "03_features/headline_labels")
